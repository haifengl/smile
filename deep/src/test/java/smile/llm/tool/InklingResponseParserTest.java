package smile.llm.tool;

import java.io.File;
import java.io.IOException;
import org.junit.jupiter.api.Assumptions;
import org.junit.jupiter.api.Test;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.ObjectMapper;
import smile.llm.FinishReason;
import static org.junit.jupiter.api.Assertions.*;

/**
 * Tests {@link InklingResponseParser} on hand-written replies and on replies generated by the oracle model.
 *
 * @author Haifeng Li
 */
public class InklingResponseParserTest {
    private final InklingResponseParser parser = new InklingResponseParser();

    @Test
    public void testGivenReasoningAndTextWhenSplitThenSeparated() {
        var p = parser.split("<|message_model|><|content_thinking|>think A<|end_message|>"
                + "<|message_model|><|content_thinking|> and B<|end_message|>"
                + "<|message_model|><|content_text|>Answer.<|end_message|><|content_model_end_sampling|>");
        assertEquals("think A and B", p.reasoning());
        assertEquals("Answer.", p.content());
        assertTrue(p.toolCalls().isEmpty());
    }

    @Test
    public void testGivenToolCallWhenParsedThenNameAndArgumentsExtracted() {
        String text = "<|message_model|><|content_thinking|>use tool<|end_message|>"
                + "<|message_model|>get_weather<|content_invoke_tool_json|>"
                + "{\"name\":\"get_weather\",\"args\":{\"city\":\"Paris\",\"unit\":\"c\"}}<|end_message|>"
                + "<|message_model|>get_weather<|content_invoke_tool_json|>"
                + "{\"name\":\"get_weather\",\"args\":{}}<|end_message|><|content_model_end_sampling|>";
        var p = parser.split(text);
        assertEquals("use tool", p.reasoning());
        assertEquals("", p.content());
        assertEquals(2, p.toolCalls().size());
        assertEquals("get_weather", p.toolCalls().get(0).function().name());
        assertEquals("{\"city\":\"Paris\",\"unit\":\"c\"}", p.toolCalls().get(0).function().arguments());
        assertEquals("{}", p.toolCalls().get(1).function().arguments());
        assertNotEquals(p.toolCalls().get(0).id(), p.toolCalls().get(1).id());
        var result = parser.parse(text);
        assertEquals(FinishReason.tool_calls, result.reason());
        assertNull(result.content());
        assertEquals(2, result.toolCalls().size());
    }

    @Test
    public void testGivenTruncatedReplyWhenSplitThenOpenMessageIsKept() {
        var p = parser.split("<|message_model|><|content_thinking|>closed<|end_message|>"
                + "<|message_model|><|content_text|>partial answ");
        assertEquals("closed", p.reasoning());
        assertEquals("partial answ", p.content());
        assertEquals(FinishReason.length, parser.parse("<|message_model|><|content_text|>cut", true).reason());
    }

    @Test
    public void testGivenFirstMessageWithoutHeaderWhenSplitThenStillParsed() {
        // The prompt side may already hold <|message_model|>; a continuation then starts at the content marker.
        var p = parser.split("<|content_thinking|>x<|end_message|><|message_model|><|content_text|>y<|end_message|>");
        assertEquals("x", p.reasoning());
        assertEquals("y", p.content());
    }

    @Test
    public void testGivenToolErrorAndFreeTextInvocationWhenSplitThenTreatedAsContent() {
        var p = parser.split("<|message_model|><|content_tool_error|>oops<|end_message|>"
                + "<|message_model|>f<|content_invoke_tool_text|>f(1)<|end_message|>");
        assertEquals("oopsf(1)", p.content());
        assertTrue(p.toolCalls().isEmpty());
    }

    @Test
    public void testGivenMalformedToolCallJsonWhenSplitThenKeptAsContent() {
        var p = parser.split("<|message_model|>f<|content_invoke_tool_json|>{\"name\": <|end_message|>");
        assertTrue(p.toolCalls().isEmpty());
        assertEquals("{\"name\": ", p.content());
    }

    @Test
    public void testGivenPlainTextWithoutMarkersWhenParsedThenReturnedAsContent() {
        var result = parser.parse("just text");
        assertEquals("just text", result.content());
        assertEquals(FinishReason.stop, result.reason());
        assertEquals("", parser.split("").content());
    }

    @Test
    public void testGivenOracleRepliesWhenSplitThenReasoningAndToolCallRecovered() throws IOException {
        File out = new File("/raid/haili/inkling/oracle/out_full.json");
        Assumptions.assumeTrue(out.exists(), "no oracle output");
        JsonNode results = new ObjectMapper().readTree(out).get("results");
        for (JsonNode r : results) {
            var p = parser.split(r.get("text").asString());
            assertFalse(p.reasoning().isEmpty(), r.get("name").asString());
            assertFalse(p.reasoning().contains("<|"), r.get("name").asString());
        }
        // The "tools" dialog reaches its tool call within the oracle's 48 generated tokens.
        var tools = parser.split(results.get(4).get("text").asString());
        assertTrue(tools.reasoning().startsWith("The user asks weather in Paris"));
    }
}
